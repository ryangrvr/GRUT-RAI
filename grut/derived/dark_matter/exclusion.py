def kinetic_mixing_estimate():
    """Estimate the kinetic mixing parameter epsilon for the GRUT dark photon.
    
    Without portal matter, epsilon = 0 at 1-loop (dark and visible sectors decouple).
    Through gravity (2-loop): epsilon ~ g_dark × e × (m_A/M_Planck)^2 ~ 10^-39.
    
    For detection, we need epsilon to be generated by SOME mechanism.
    Possible sources:
    1. Gravitational: ~10^-39 (undetectable)
    2. If heavy portal matter exists at M_portal: epsilon ~ g_dark × e / (16 pi^2) × (m_A/M_portal)^2
    3. If portal at TeV: epsilon ~ 10^-5 to 10^-3 (detectable!)
    """
    g_dark = 0.917
    e = np.sqrt(4 * np.pi / 137.036)
    m_A = 0.387  # GeV
    M_Pl = 2.435e18  # GeV
    
    eps_gravitational = g_dark * e * (m_A / M_Pl)**2
    eps_tev_portal = g_dark * e / (16 * np.pi**2) * (m_A / 1000)**2
    eps_100gev_portal = g_dark * e / (16 * np.pi**2) * (m_A / 100)**2
    
    return {
        "gravitational_only": {
            "epsilon": eps_gravitational, "epsilon2": eps_gravitational**2,
            "detectable": False, "note": "Pure gravity: ~10^-39, undetectable by any experiment",
        },
        "TeV_portal": {
            "epsilon": eps_tev_portal, "epsilon2": eps_tev_portal**2,
            "detectable": eps_tev_portal**2 > 1e-10,
            "note": "Portal at 1 TeV: detectable by SHiP",
        },
        "100GeV_portal": {
            "epsilon": eps_100gev_portal, "epsilon2": eps_100gev_portal**2,
            "detectable": eps_100gev_portal**2 > 1e-8,
            "note": "Portal at 100 GeV: detectable by Belle II, LHCb",
        },
        "detection_threshold": {
            "current_best": 1e-7, "experiment": "NA62/Belle II",
            "future_best": 1e-10, "experiment_future": "SHiP",
            "grut_needs": "Portal matter OR non-minimal dark sector coupling",
        },
    }


def exclusion_status():
    """Is the GRUT dark photon already excluded by any experiment?"""
    m_A = 387.4  # MeV
    results = {}
    
    for name, exp in EXPERIMENTS.items():
        in_mass_range = exp["mass_range_MeV"][0] <= m_A <= exp["mass_range_MeV"][1]
        results[name] = {
            "in_mass_range": in_mass_range,
            "epsilon2_limit": exp["epsilon2_limit_at_387"],
            "status": exp["status"],
            "channel": exp["channel"],
            "excluded_if_epsilon2_above": exp["epsilon2_limit_at_387"] if in_mass_range else None,
        }
    
    # The GRUT dark photon is NOT excluded because:
    # 1. Without kinetic mixing (epsilon = 0), it doesn't couple to SM
    # 2. Experiments only constrain epsilon × production, not the dark photon existence
    
    return {
        "mass_MeV": m_A,
        "experiments": results,
        "is_excluded": False,
        "reason": (
            "The GRUT dark photon at 387 MeV is NOT excluded. "
            "Existing limits constrain the kinetic mixing parameter epsilon, "
            "not the dark photon mass. Without a portal coupling, the dark photon "
            "is invisible to all current experiments. The question is not 'does it exist?' "
            "but 'how strongly does it mix with the SM photon?'"
        ),
    }


def detection_roadmap():
    """Timeline and requirements for detecting the 387 MeV dark photon."""
    mixing = kinetic_mixing_estimate()
    
    roadmap = []
    for name, exp in sorted(EXPERIMENTS.items(), key=lambda x: x[1].get("year", 2099)):
        eps2_limit = exp["epsilon2_limit_at_387"]
        projected = exp.get("projected_epsilon2_at_387", eps2_limit)
        
        # Can this experiment reach the TeV portal scenario?
        eps2_tev = mixing["TeV_portal"]["epsilon2"]
        eps2_100 = mixing["100GeV_portal"]["epsilon2"]
        
        roadmap.append({
            "experiment": name,
            "year": exp.get("year", "?"),
            "status": exp["status"],
            "epsilon2_reach": eps2_limit,
            "projected_reach": projected,
            "reaches_tev_portal": projected < eps2_tev if eps2_tev > 0 else False,
            "reaches_100gev_portal": projected < eps2_100 if eps2_100 > 0 else False,
            "channel": exp["channel"],
        })
    
    return {
        "target": {"mass_MeV": 387.4, "g_dark": 0.917},
        "roadmap": roadmap,
        "best_near_term": "Belle II (running, e+e- ISR) or LHCb Run 3 (running, dimuon)",
        "best_future": "SHiP (proposed, reaches epsilon^2 ~ 10^-10)",
        "key_question": "Does portal matter exist? If yes → detectable. If no → invisible.",
        "grut_prediction": "The dark photon EXISTS at 387 MeV regardless of epsilon. Detection depends on the coupling to SM.",
    }


